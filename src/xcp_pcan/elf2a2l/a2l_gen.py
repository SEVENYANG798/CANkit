"""Generate ASAP2 A2L text from Variable list (project style)."""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from .elf_extract import MemSection, Variable
from .types_map import STANDARD_COMPU_METHODS, STANDARD_RECORD_LAYOUTS


def _fmt_addr(addr: int) -> str:
    return f"0x{addr:08X}"


def measurement_block(var: Variable) -> str:
    t = var.a2l_type
    lines = [
        "  /begin MEASUREMENT ",
        f"    /* Name                   */      {var.name}",
        '    /* Long identifier        */      ""',
        f"    /* Data type              */      {t.a2l_dtype}",
        f"    /* Conversion method      */      {t.compu_method}",
        "    /* Resolution (Not used)  */      0      ",
        "    /* Accuracy (Not used)    */      0      ",
        f"    /* Lower limit            */      {t.lower}",
        f"    /* Upper limit            */      {t.upper}",
        f"    ECU_ADDRESS                       {_fmt_addr(var.address)}",
    ]
    # Known C array: ARRAY_SIZE is the element count, not the byte count.
    if var.array_dims and all(d > 0 for d in var.array_dims):
        count = 1
        for dim in var.array_dims:
            count *= dim
        if count > 1:
            if len(var.array_dims) == 1:
                lines.append(f"    ARRAY_SIZE                        {count}")
            else:
                dims = " ".join(str(d) for d in var.array_dims)
                lines.append(f"    MATRIX_DIM                        {dims}")
    elif var.size > t.size:
        lines.append(f"    ARRAY_SIZE                        {var.size}")
    lines.append("  /end MEASUREMENT ")
    lines.append("")
    return "\n".join(lines)


def characteristic_block(var: Variable) -> str:
    t = var.a2l_type
    return "\n".join(
        [
            "  /begin CHARACTERISTIC ",
            f"    /* Name                   */      {var.name}",
            '    /* Long Identifier        */      ""',
            "    /* Type                   */      VALUE",
            f"    /* ECU Address            */      {_fmt_addr(var.address)}",
            f"    /* Record Layout          */      {t.record_layout}",
            "    /* Maximum Difference     */      0",
            f"    /* Conversion Method      */      {t.compu_method}",
            f"    /* Lower Limit            */      {t.lower}",
            f"    /* Upper Limit            */      {t.upper}",
            "  /end CHARACTERISTIC ",
            "",
        ]
    )


def _compu_methods_text() -> str:
    lines: list[str] = []
    for name, fmt, unit in STANDARD_COMPU_METHODS:
        lines.append(
            "\n".join(
                [
                    "  /begin COMPU_METHOD",
                    f"    /* Name of CompuMethod    */      {name}",
                    '    /* Long identifier        */      "Q = V"',
                    "    /* Conversion Type        */      IDENTICAL",
                    f'    /* Format                 */      "{fmt}"',
                    f'    /* Units                  */      "{unit}"',
                    "  /end COMPU_METHOD",
                    "",
                ]
            )
        )
    return "\n".join(lines)


def _record_layouts_text() -> str:
    lines: list[str] = []
    for name, dtype in STANDARD_RECORD_LAYOUTS:
        lines.append(
            "\n".join(
                [
                    f"  /begin  RECORD_LAYOUT {name}",
                    f"    FNC_VALUES 1 {dtype} COLUMN_DIR DIRECT",
                    "  /end  RECORD_LAYOUT ",
                    "",
                ]
            )
        )
    return "\n".join(lines)


def generate_a2l(
    variables: list[Variable],
    *,
    project_name: str = "ELF_XCP",
    module_name: str = "ModuleName",
    as_characteristic: bool = False,
    elf_path: str | None = None,
) -> str:
    """Create a complete A2L document matching the style under A2L/."""
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    elf_note = Path(elf_path).name if elf_path else ""
    header = f"""\
/******************************************************************************
 *
 *  ASAP2 file:     {project_name}.a2l
 *
 *  Generated by toa2l (elf2a2l) for XCP measurement.
 *  Source ELF: {elf_note}
 *  Generated on: {stamp}
 *  Variable count: {len(variables)}
 *
 ******************************************************************************/
ASAP2_VERSION  1 71     /* Version 1.71 */

/begin PROJECT {project_name} "Generated from ELF globals"

  /begin HEADER "Header Comments go here"
  /end HEADER

  /begin MODULE {module_name}  "Module Comment Goes Here"

    /begin MOD_PAR "MOD PAR Comment Goes Here"
    /end MOD_PAR

    /begin MOD_COMMON  "Mod Common Comment Here"
      BYTE_ORDER     MSB_LAST

      ALIGNMENT_BYTE 1
      ALIGNMENT_WORD 2
      ALIGNMENT_LONG 4
      ALIGNMENT_FLOAT32_IEEE 4
      ALIGNMENT_FLOAT64_IEEE 8
      ALIGNMENT_INT64 8
    /end MOD_COMMON

"""
    body_parts: list[str] = []
    ref_meas: list[str] = []
    ref_char: list[str] = []
    for var in variables:
        if as_characteristic:
            body_parts.append(characteristic_block(var))
            ref_char.append(var.name)
        else:
            body_parts.append(measurement_block(var))
            ref_meas.append(var.name)

    group = [
        "  /begin GROUP",
        f"    /* Name                   */      {project_name}_Globals",
        '    /* Long identifier        */      "ELF global variables"',
        "    /* Root                   */      ROOT",
    ]
    if ref_meas:
        group.append("    /begin REF_MEASUREMENT")
        for n in ref_meas:
            group.append(f"      {n}")
        group.append("    /end REF_MEASUREMENT")
    if ref_char:
        group.append("    /begin REF_CHARACTERISTIC")
        for n in ref_char:
            group.append(f"      {n}")
        group.append("    /end REF_CHARACTERISTIC")
    group.append("  /end GROUP")
    group.append("")

    footer = """
  /end MODULE

/end PROJECT
/* EOF */
"""
    return (
        header
        + "\n".join(body_parts)
        + "\n"
        + _compu_methods_text()
        + "\n"
        + _record_layouts_text()
        + "\n"
        + "\n".join(group)
        + footer
    )


def measurements_snippet(variables: list[Variable]) -> str:
    """Only MEASUREMENT blocks (for inserting into an existing MODULE)."""
    return "\n".join(measurement_block(v) for v in variables)


def _segment_ident(name: str, used: set[str]) -> str:
    ident = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_")
    if not ident or ident[0].isdigit():
        ident = "SEG_" + ident
    base = ident
    n = 2
    while ident in used:
        ident = f"{base}_{n}"
        n += 1
    used.add(ident)
    return ident


def is_cal_section(name: str) -> bool:
    upper = name.upper()
    return "CAL" in upper and not upper.endswith("_ROM")


def _cal_page_if_data(segment_number: int) -> list[str]:
    """Two pages: 0 is the reference page, 1 is the working page CANape writes."""
    seg = f"0x{segment_number:02X}"
    return [
        "        /begin IF_DATA XCPplus",
        "          0x0102",
        "          /begin SEGMENT",
        f"            {seg}",
        "            0x02",
        "            0x00",
        "            0x00",
        "            0x00",
        "            /begin CHECKSUM",
        "              XCP_CRC_32",
        "              MAX_BLOCK_SIZE 256",
        "            /end CHECKSUM",
        "            /begin PAGE",
        "              0x00",
        "              ECU_ACCESS_DONT_CARE",
        "              XCP_READ_ACCESS_DONT_CARE",
        "              XCP_WRITE_ACCESS_NOT_ALLOWED",
        "            /end PAGE",
        "            /begin PAGE",
        "              0x01",
        "              ECU_ACCESS_DONT_CARE",
        "              XCP_READ_ACCESS_DONT_CARE",
        "              XCP_WRITE_ACCESS_WITH_ECU_ONLY",
        "            /end PAGE",
        "          /end SEGMENT",
        "        /end IF_DATA",
    ]


def memory_segments_block(sections: list[MemSection]) -> str:
    """MOD_PAR whose segments follow the ELF, so every global address is covered.

    Writable *CAL* sections get an XCP calibration segment. Page 1 is writable,
    which is what CANape needs before DOWNLOAD.
    """
    used: set[str] = set()
    lines = [
        '    /begin MOD_PAR "segments from ELF"',
    ]
    xcp_segment = 0
    for sec in sections:
        ident = _segment_ident(sec.name, used)
        if sec.executable:
            mem_type, attr = "CODE", "FLASH"
        elif sec.writable:
            mem_type, attr = "DATA", "RAM"
        else:
            mem_type, attr = "DATA", "FLASH"
        lines.append("      /begin MEMORY_SEGMENT")
        lines.append(
            f"        {ident} \"{sec.name}\" {mem_type} {attr} INTERN "
            f"0x{sec.address:X} 0x{sec.size:X} -1 -1 -1 -1 -1"
        )
        if sec.writable and is_cal_section(sec.name) and xcp_segment < 5:
            lines.extend(_cal_page_if_data(xcp_segment))
            xcp_segment += 1
        lines.append("      /end MEMORY_SEGMENT")
    lines.append("    /end MOD_PAR")
    return "\n".join(lines)


def _replace_block(text: str, keyword: str, new_block: str) -> str:
    begin = f"/begin {keyword}"
    end = f"/end {keyword}"
    start = text.find(begin)
    if start < 0:
        return text
    depth = 0
    i = start
    while i < len(text):
        next_begin = text.find(begin, i)
        next_end = text.find(end, i)
        if next_end < 0:
            return text
        if next_begin != -1 and next_begin <= next_end:
            depth += 1
            i = next_begin + len(begin)
            continue
        depth -= 1
        i = next_end + len(end)
        if depth == 0:
            return text[:start] + new_block + text[i:]
    return text


def normalize_can_id(value: str | None, default: str) -> str:
    text = (value or "").strip()
    if not text:
        return default
    raw = text[2:] if text.lower().startswith("0x") else text
    return "0x" + format(int(raw, 16), "X")


def patch_can_ids(text: str, master: str | None, slave: str | None) -> str:
    """Overwrite CAN IDs when provided; leave template values when None/empty."""
    if master is not None and str(master).strip():
        master_id = normalize_can_id(master, DEFAULT_CAN_ID_MASTER)
        text = re.sub(
            r"(CAN_ID_MASTER\s+)0x[0-9A-Fa-f]+",
            rf"\g<1>{master_id}",
            text,
            count=1,
        )
    if slave is not None and str(slave).strip():
        slave_id = normalize_can_id(slave, DEFAULT_CAN_ID_SLAVE)
        text = re.sub(
            r"(CAN_ID_SLAVE\s+)0x[0-9A-Fa-f]+",
            rf"\g<1>{slave_id}",
            text,
            count=1,
        )
    return text


MARKER = "/* @@ELF_MEASUREMENTS@@ */"

# Templete_FR defaults (left-zone FL uses 0x6A8 / 0x400006A9).
# Hex is normalized without leading zeros (same as normalize_can_id).
DEFAULT_CAN_ID_MASTER = "0x6A6"
DEFAULT_CAN_ID_SLAVE = "0x400006A7"

# N82 project header shells from N82_A2L_v3 (FR = right zone, FL = left zone).
BUNDLED_TEMPLATES: tuple[tuple[str, str, str, str], ...] = (
    ("Templete_FR", "Templete_FR.a2l", DEFAULT_CAN_ID_MASTER, DEFAULT_CAN_ID_SLAVE),
    ("Templete_FL", "Templete_FL.a2l", "0x6A8", "0x400006A9"),
)


def _templates_dir() -> Path:
    import sys

    bundled = Path(__file__).resolve().parent / "templates"
    if bundled.is_dir():
        return bundled
    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        frozen = Path(meipass) / "xcp_pcan" / "elf2a2l" / "templates"
        if frozen.is_dir():
            return frozen
    return bundled


def bundled_template_path(name: str) -> Path:
    return _templates_dir() / name


def default_template_path() -> Path:
    """Prefer Templete_FR; fall back to legacy xcp_fr.a2l."""
    fr = bundled_template_path("Templete_FR.a2l")
    if fr.is_file():
        return fr
    legacy = bundled_template_path("xcp_fr.a2l")
    return legacy if legacy.is_file() else fr


def parse_template_can_ids(text: str) -> tuple[str | None, str | None]:
    """Read the first CAN_ID_MASTER / CAN_ID_SLAVE values from a template."""
    master = slave = None
    m = re.search(r"CAN_ID_MASTER\s+(0x[0-9A-Fa-f]+)", text)
    if m:
        master = normalize_can_id(m.group(1), DEFAULT_CAN_ID_MASTER)
    m = re.search(r"CAN_ID_SLAVE\s+(0x[0-9A-Fa-f]+)", text)
    if m:
        slave = normalize_can_id(m.group(1), DEFAULT_CAN_ID_SLAVE)
    return master, slave


def _variable_blocks(variables: list[Variable]) -> str:
    parts: list[str] = []
    for var in variables:
        if is_cal_section(var.section) and not var.array_dims and var.size <= var.a2l_type.size:
            parts.append(characteristic_block(var))
        else:
            parts.append(measurement_block(var))
    return "\n".join(parts)


def fill_template(
    template_text: str,
    variables: list[Variable],
    sections: list[MemSection],
    *,
    elf_path: str | None = None,
    can_id_master: str | None = None,
    can_id_slave: str | None = None,
) -> str:
    """Insert variables and replace MOD_PAR segments with the ELF memory map.

    XCP transport (CAN ID, baud, events) stays in the template.
    """
    note = Path(elf_path).name if elf_path else ""
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    banner = (
        f"\n    /* elf2a2l {stamp}  elf={note}  count={len(variables)} */\n\n"
        + _variable_blocks(variables)
        + "\n"
        + _compu_methods_text()
        + "\n"
        + _record_layouts_text()
    )
    text = patch_can_ids(template_text, can_id_master, can_id_slave)
    if sections:
        text = _replace_block(text, "MOD_PAR", memory_segments_block(sections))
    if MARKER in text:
        return text.replace(MARKER, banner, 1)
    idx = text.rfind("/end MODULE")
    if idx < 0:
        raise ValueError("template has no /end MODULE")
    return text[:idx] + banner + "\n" + text[idx:]
